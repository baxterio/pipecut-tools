type StrokeIconName = keyof typeof STROKE_ICONS;
type SolidIconName = keyof typeof SOLID_ICONS;

export type IconName = StrokeIconName | SolidIconName;

interface IconProps {
  name: IconName;
  /** Côté de l'icône, en pixels. */
  size?: number;
  className?: string;
}

function isStroke(name: IconName): name is StrokeIconName {
  return name in STROKE_ICONS;
}

/** Icône décorative : le texte voisin porte le sens, elle est masquée aux lecteurs d'écran. */
export function Icon({ name, size = 16, className }: IconProps) {
  const stroke = isStroke(name);
  return (
    <svg
      className={[styles.icon, stroke ? styles.stroke : styles.solid, className].filter(Boolean).join(" ")}
      viewBox="0 0 24 24"
      width={size}
      height={size}
      aria-hidden="true"
      focusable="false"
      data-icon={name}
    >
      {stroke ? STROKE_ICONS[name] : <path d={SOLID_ICONS[name]} />}
    </svg>
  );
}
